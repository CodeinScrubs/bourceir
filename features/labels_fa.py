def format_feature(name: str, value) -> str:
    """نمایش خوانای مقدار فیچر (ارقام لاتین؛ برای جدول)."""
    import pandas as pd

    if value is None or pd.isna(value):  # شامل NaN از نوع float32 نامپای
        return "—"
    value = float(value)
    kind = FEATURE_LABELS_FA.get(name, ("", "", "num"))[2]
    if kind == "pct":
        return f"{value * 100:+.2f}%"
    if kind == "flag":
        return "بله" if value >= 0.5 else "خیر"
    if kind == "int":
        return f"{int(value):,}"
    return f"{value:,.2f}"
